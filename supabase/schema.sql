create or replace function public.validate_calendar_slot() returns trigger language plpgsql set search_path = pg_catalog, public as $$
begin
  perform pg_advisory_xact_lock(8127331);
  if tg_table_name = 'appointments' then
    if new.status <> 'cancelled' and exists (
      select 1 from public.blocked_times b where new.start_time < b.end_time and new.end_time > b.start_time
    ) then raise exception using errcode='23P01', message='Appointment overlaps blocked time'; end if;
  elsif tg_table_name = 'blocked_times' then
    if exists (
      select 1 from public.appointments a where a.status <> 'cancelled' and a.deleted_at is null and new.start_time < a.end_time and new.end_time > a.start_time
    ) then raise exception using errcode='23P01', message='Blocked time overlaps appointment'; end if;
  end if;
  return new;
end $$;
create or replace function public.validate_appointment_transition() returns trigger language plpgsql set search_path = pg_catalog, public as $$
begin
  if tg_op='INSERT' then
    if new.status<>'pending' then raise exception using errcode='23514', message='New appointments must start pending'; end if;
    return new;
  end if;
  if old.status = new.status then return new; end if;
  if old.status in ('completed','cancelled') then raise exception using errcode='23514', message='Terminal appointment status cannot be changed'; end if;
  if not ((old.status='pending' and new.status in ('confirmed','cancelled')) or (old.status='confirmed' and new.status in ('in_service','cancelled')) or (old.status='in_service' and new.status='cancelled') or (old.status='in_service' and new.status='completed' and current_setting('app.checkout_appointment_id',true)=new.id::text)) then
    raise exception using errcode='23514', message='Invalid appointment state transition; completion requires checkout';
  end if; return new;
end $$;


create or replace function public.create_appointment(p_customer_id bigint,p_service_id bigint,p_start_time timestamptz,p_status text default 'pending',p_custom_items jsonb default '[]',p_note text default null)
returns public.appointments language plpgsql security invoker set search_path = pg_catalog, public as $$
declare v_duration integer; v_price bigint; v_result public.appointments;
begin
  if p_status <> 'pending' then raise exception 'New appointments must start pending'; end if;
  select duration_min,price into strict v_duration,v_price from public.services where id=p_service_id and active;
  insert into public.appointments(customer_id,service_id,start_time,end_time,status,total_amount,custom_items,note)
  values(p_customer_id,p_service_id,p_start_time,p_start_time+make_interval(mins=>v_duration),'pending',v_price,coalesce(p_custom_items,'[]'),p_note) returning * into v_result;
  return v_result;
end $$;
create or replace function public.update_appointment(p_id bigint,p_customer_id bigint,p_service_id bigint,p_start_time timestamptz,p_status text,p_custom_items jsonb default '[]',p_note text default null)
returns public.appointments language plpgsql security invoker set search_path = pg_catalog, public as $$
declare v_duration integer; v_result public.appointments;
begin
  select duration_min into strict v_duration from public.services where id=p_service_id;
  update public.appointments set customer_id=p_customer_id,service_id=p_service_id,start_time=p_start_time,end_time=p_start_time+make_interval(mins=>v_duration),status=p_status::public.appointment_status,custom_items=coalesce(p_custom_items,'[]'),note=p_note where id=p_id returning * into strict v_result;
  return v_result;
end $$;
create or replace function public.adjust_product_stock(p_product_id bigint,p_quantity_delta integer,p_reason text) returns integer
language plpgsql security invoker set search_path = pg_catalog, public as $$ declare v_stock integer; begin
  if p_quantity_delta=0 or btrim(p_reason)='' then raise exception 'A non-zero delta and reason are required'; end if;
  update public.products set stock=stock+p_quantity_delta where id=p_product_id and stock+p_quantity_delta>=0 returning stock into v_stock;
  if not found then raise exception 'Product missing or insufficient stock'; end if;
  insert into public.stock_adjustments(product_id,quantity_delta,resulting_stock,reason) values(p_product_id,p_quantity_delta,v_stock,p_reason); return v_stock;
end $$;
create or replace function public.update_product(p_product_id bigint,p_name text,p_price bigint,p_stock integer,p_vendor text default null,p_active boolean default true)
returns integer language plpgsql security invoker set search_path = pg_catalog, public as $$
declare v_previous integer; v_delta integer;
begin
  if btrim(coalesce(p_name,''))='' or p_price<0 or p_stock<0 then raise exception 'Invalid product values'; end if;
  select stock into strict v_previous from public.products where id=p_product_id for update;
  update public.products set name=btrim(p_name),price=p_price,stock=p_stock,vendor=nullif(btrim(coalesce(p_vendor,'')),''),active=p_active where id=p_product_id;
  v_delta:=p_stock-v_previous;
  if v_delta<>0 then insert into public.stock_adjustments(product_id,quantity_delta,resulting_stock,reason) values(p_product_id,v_delta,p_stock,'Inline stock edit'); end if;
  return p_stock;
end $$;
create or replace function public.checkout_appointment(p_appointment_id bigint,p_idempotency_key text,p_product_items jsonb default '[]',p_custom_items jsonb default '[]',p_payment_method text default 'cash',p_discount bigint default 0)
returns table(order_id bigint,total_amount bigint) language plpgsql security invoker set search_path = pg_catalog, public as $$
declare v_app public.appointments; v_order public.orders; v_service_name text; v_service_amount bigint; v_product_amount bigint:=0; v_custom_amount bigint:=0; v_item jsonb; v_product public.products; v_qty integer; v_total bigint;
begin
  -- Lock first so concurrent retries serialize before checking the idempotency record.
  select * into strict v_app from public.appointments where id=p_appointment_id for update;
  select * into v_order from public.orders where idempotency_key=p_idempotency_key;
  if found then if v_order.appointment_id<>p_appointment_id then raise exception 'Idempotency key already used'; end if; return query select v_order.id,v_order.total_amount; return; end if;
  if exists(select 1 from public.orders where appointment_id=p_appointment_id) then raise exception 'Appointment was already checked out with another idempotency key'; end if;
  if v_app.status<>'in_service' then raise exception 'Only in-service appointments can be checked out'; end if;
  select name,price into strict v_service_name,v_service_amount from public.services where id=v_app.service_id;
  if jsonb_typeof(coalesce(p_product_items,'[]'))<>'array' or jsonb_typeof(coalesce(p_custom_items,'[]'))<>'array' or p_discount<0 or p_payment_method not in ('cash','line_pay') then raise exception 'Invalid checkout items, discount, or payment method'; end if;
  for v_item in select value from jsonb_array_elements(coalesce(p_product_items,'[]')) loop
    v_qty=(v_item->>'quantity')::integer; if v_qty<=0 then raise exception 'Product quantity must be positive'; end if;
    select * into strict v_product from public.products where id=(v_item->>'product_id')::bigint for update;
    if not v_product.active or v_product.stock<v_qty then raise exception 'Product unavailable or insufficient stock'; end if;
    v_product_amount:=v_product_amount+(v_product.price*v_qty);
  end loop;
  for v_item in select value from jsonb_array_elements(coalesce(p_custom_items,'[]')) loop
    if btrim(coalesce(v_item->>'name',''))='' or (v_item->>'amount')::bigint<0 then raise exception 'Invalid custom item'; end if; v_custom_amount:=v_custom_amount+(v_item->>'amount')::bigint;
  end loop;
  v_total:=greatest(0,v_service_amount+v_product_amount+v_custom_amount-p_discount);
  insert into public.orders(appointment_id,idempotency_key,service_amount,product_amount,custom_amount,discount,total_amount,payment_method,custom_items) values(p_appointment_id,p_idempotency_key,v_service_amount,v_product_amount,v_custom_amount,p_discount,v_total,p_payment_method,coalesce(p_custom_items,'[]')) returning * into v_order;
  insert into public.order_items(order_id,item_type,name,quantity,unit_amount,line_amount) values(v_order.id,'service',v_service_name,1,v_service_amount,v_service_amount);
  for v_item in select value from jsonb_array_elements(coalesce(p_product_items,'[]')) loop
    v_qty=(v_item->>'quantity')::integer; select * into strict v_product from public.products where id=(v_item->>'product_id')::bigint for update;
    update public.products set stock=stock-v_qty where id=v_product.id and active and stock>=v_qty returning stock into v_product.stock;
    if not found then raise exception 'Product unavailable or insufficient stock'; end if;
    insert into public.order_items(order_id,item_type,product_id,name,quantity,unit_amount,line_amount) values(v_order.id,'product',v_product.id,v_product.name,v_qty,v_product.price,v_product.price*v_qty);
    insert into public.stock_adjustments(product_id,order_id,quantity_delta,resulting_stock,reason) values(v_product.id,v_order.id,-v_qty,v_product.stock,'Checkout');
  end loop;
  for v_item in select value from jsonb_array_elements(coalesce(p_custom_items,'[]')) loop insert into public.order_items(order_id,item_type,name,quantity,unit_amount,line_amount) values(v_order.id,'custom',v_item->>'name',1,(v_item->>'amount')::bigint,(v_item->>'amount')::bigint); end loop;
  -- Transaction-local capability lets only this RPC perform the atomic completion transition.
  perform set_config('app.checkout_appointment_id',p_appointment_id::text,true);
  update public.appointments set status='completed',total_amount=v_total,custom_items=coalesce(p_custom_items,'[]') where id=p_appointment_id;
  return query select v_order.id,v_order.total_amount;
end $$;

create or replace function public.archive_appointment(p_appointment_id bigint)
returns bigint language plpgsql security invoker set search_path = pg_catalog, public as $$
declare v_appointment public.appointments; v_order public.orders; v_line record; v_resulting_stock integer; v_voided_at timestamptz;
begin
  select * into v_appointment from public.appointments where id=p_appointment_id for update;
  if not found then raise exception 'Appointment not found'; end if;
  v_voided_at:=coalesce(v_appointment.deleted_at,now());
  select * into v_order from public.orders where appointment_id=p_appointment_id for update;
  if found and v_order.voided_at is null then
    for v_line in select product_id,sum(quantity)::integer quantity from public.order_items where order_id=v_order.id and item_type='product' group by product_id order by product_id loop
      update public.products set stock=stock+v_line.quantity where id=v_line.product_id returning stock into v_resulting_stock;
      if not found then raise exception 'Product % not found while voiding order %',v_line.product_id,v_order.id; end if;
      insert into public.stock_adjustments(product_id,order_id,quantity_delta,resulting_stock,reason) values(v_line.product_id,v_order.id,v_line.quantity,v_resulting_stock,'Voided archived appointment');
    end loop;
    update public.orders set voided_at=v_voided_at,void_reason='Appointment archived' where id=v_order.id and voided_at is null;
  end if;
  update public.finance_records set voided_at=coalesce(voided_at,v_voided_at),void_reason=coalesce(void_reason,'Appointment archived'),updated_at=now()
  where appointment_id=p_appointment_id or (v_order.id is not null and order_id=v_order.id);
  update public.appointments set deleted_at=coalesce(deleted_at,v_voided_at) where id=p_appointment_id;
  return p_appointment_id;
end $$;

